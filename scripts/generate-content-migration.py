"""Generate the prototype content migration from a MyRumbo export.

Inputs (kept outside the repo, in the Grid Professor project folder's prototype-inputs/):
  myrumbo-two-chapters.json   read-only export of two excel-for-finance chapters
  descriptors/*.descriptor.yaml  MyRumbo descriptor files for the same videos

Usage:
  python3 scripts/generate-content-migration.py <prototype-inputs dir> > supabase/migrations/<ts>_prototype_content.sql

Tags written here are basis 'claimed': they come from AI-extracted descriptors and
hand-mapped topics, not from an author's declaration or an observed formula.
"""

import json
import re
import sys
from pathlib import Path

import yaml

INPUT = Path(sys.argv[1])
EXCLUDE = {"ex-prep-guidance"}  # teaches the old xPrep download routine the add-in replaces

TEMPLATE = {
    "slug": "excel-for-finance-tvm",
    "title": "Excel for Finance: Discounting and Annuities",
    "summary": "Present value, future value and annuities, built in Excel one model at a time.",
}
UNITS = {
    "discounting-exercises": ("discounting", "Discounting", "Present and future value of single cash flows and series."),
    "annuities-exercises": ("annuities", "Annuities", "Ordinary, due, deferred and growing annuities, plus the flag logic that models them."),
}
LIBRARY_EXPLAINERS = ["pv-and-cell-references", "if-and-or", "flags"]

TOPICS = {
    "time-value-of-money": "Time value of money",
    "present-value": "Present value",
    "future-value": "Future value",
    "discount-factor": "Discount factor",
    "compounding": "Compounding",
    "compounding-frequency": "Compounding frequency",
    "annuity": "Annuity",
    "annuity-due": "Annuity due",
    "deferred-annuity": "Deferred annuity",
    "growing-annuity": "Growing annuity",
    "growing-perpetuity": "Growing perpetuity",
    "conditional-cash-flows": "Conditional cash flows",
}
ITEM_TOPICS = {
    "discounting-exercise-1": ["present-value", "discount-factor"],
    "discounting-exercise-2": ["present-value", "discount-factor"],
    "discounting-exercise-3": ["future-value", "compounding"],
    "discounting-exercise-4": ["future-value", "compounding"],
    "discounting-exercise-5": ["present-value", "compounding-frequency"],
    "pv-and-cell-references": ["present-value", "annuity"],
    "if-and-or": ["conditional-cash-flows"],
    "flags": ["conditional-cash-flows"],
    "annuities-exercise-1": ["present-value", "annuity"],
    "annuities-exercise-2": ["annuity", "annuity-due"],
    "annuities-exercise-3": ["annuity", "deferred-annuity"],
    "annuities-exercise-4": ["growing-annuity", "deferred-annuity"],
    "annuities-exercise-5": ["growing-perpetuity", "growing-annuity"],
}
TECHNIQUES = {"absolute-references": ("Absolute and relative references (F4)", re.compile(r"\bF4\b|anchor|absolute|lock", re.I))}


def q(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def main():
    export = json.loads((INPUT / "myrumbo-two-chapters.json").read_text(encoding="utf-8"))
    descriptors = {}
    for path in (INPUT / "descriptors").glob("*.descriptor.yaml"):
        d = yaml.safe_load(path.read_text(encoding="utf-8"))
        descriptors[d["slug"]] = d

    rows = [r for r in export["rows"] if r["videos"]["slug"] not in EXCLUDE and not r["is_hidden"]]
    missing = [r["videos"]["slug"] for r in rows if r["videos"]["slug"] not in descriptors]
    if missing:
        sys.exit(f"descriptors missing for: {missing}")

    out = []
    w = out.append
    w("-- Prototype content: two excel-for-finance chapters from MyRumbo as a template course.")
    w(f"-- Generated by scripts/generate-content-migration.py from an export taken {export['exported_at']}.")
    w("-- Videos and readings only. David's add-in workbooks are added when his inventory arrives.")
    w("")
    w("insert into public.owners (slug, name, type) values ('not-established', 'Not established', 'not_established');")
    w("")

    for slug, name in TOPICS.items():
        w(f"insert into public.topics (slug, name) values ({q(slug)}, {q(name)});")
    functions = sorted({f for d in descriptors.values() for f in (d.get("excel_functions_used") or [])})
    for f in functions:
        w(f"insert into public.skills (slug, name, type) values ({q(f.lower())}, {q(f)}, 'function');")
    for slug, (name, _) in TECHNIQUES.items():
        w(f"insert into public.skills (slug, name, type) values ({q(slug)}, {q(name)}, 'technique');")
    w("")

    owner = "(select id from public.owners where slug = 'not-established')"
    for r in rows:
        v = r["videos"]
        d = descriptors[v["slug"]]
        title = r["display_title"] or v["title"]
        summary = (v.get("summary") or d.get("summary") or "").strip() or None
        source = "myrumbo:excel-for-finance (WhisperX transcript, Vimeo upload)"
        w(f"-- {v['slug']}")
        w(
            "insert into public.items (slug, kind, title, summary, owner_id, stored_at, duration_seconds, origin, source) values "
            f"({q(v['slug'])}, 'video', {q(title)}, {q(summary)}, {owner}, {q(v['video_url'])}, {q(v['duration_seconds'])}, 'primitive', {q(source)});"
        )
        read = (r.get("display_read_content") or v.get("read_content") or "").strip()
        if read:
            w(
                "insert into public.items (slug, kind, title, summary, owner_id, body_md, origin, derived_from, source) values "
                f"({q(v['slug'] + '--read')}, 'read', {q(title + ': reading')}, {q(summary)}, {owner}, {q(read)}, 'derived', "
                f"(select id from public.items where slug = {q(v['slug'])}), 'myrumbo descriptor prompt (read_content)');"
            )
        item_ref = f"(select id from public.items where slug = {q(v['slug'])})"
        for f in d.get("excel_functions_used") or []:
            w(f"insert into public.item_skills (item_id, skill_id, basis) values ({item_ref}, (select id from public.skills where slug = {q(f.lower())}), 'claimed');")
        text = " ".join((d.get("covers") or []) + [read])
        for slug, (_, pattern) in TECHNIQUES.items():
            if pattern.search(text):
                w(f"insert into public.item_skills (item_id, skill_id, basis) values ({item_ref}, (select id from public.skills where slug = {q(slug)}), 'claimed');")
        for t in ["time-value-of-money"] + ITEM_TOPICS[v["slug"]]:
            w(f"insert into public.item_topics (item_id, topic_id, basis) values ({item_ref}, (select id from public.topics where slug = {q(t)}), 'claimed');")

        # One module per video: slot 1 holds the video and its reading as substitutes.
        w(f"insert into public.modules (slug, title, summary) values ({q(v['slug'])}, {q(title)}, {q(summary)});")
        w(f"insert into public.module_slots (module_id, position) values ((select id from public.modules where slug = {q(v['slug'])}), 1);")
        slot = f"(select s.id from public.module_slots s join public.modules m on m.id = s.module_id where m.slug = {q(v['slug'])} and s.position = 1)"
        w(f"insert into public.slot_items (slot_id, item_id, position) values ({slot}, {item_ref}, 1);")
        if read:
            w(f"insert into public.slot_items (slot_id, item_id, position) values ({slot}, (select id from public.items where slug = {q(v['slug'] + '--read')}), 2);")
        w("")

    w(f"insert into public.courses (slug, title, summary, kind) values ({q(TEMPLATE['slug'])}, {q(TEMPLATE['title'])}, {q(TEMPLATE['summary'])}, 'template');")
    course = f"(select id from public.courses where slug = {q(TEMPLATE['slug'])})"
    chapters = sorted({(r["course_chapters"]["chapter_order"], r["course_chapters"]["slug"]) for r in rows})
    for unit_pos, (_, chapter_slug) in enumerate(chapters, start=1):
        unit_slug, unit_title, unit_summary = UNITS[chapter_slug]
        w(f"insert into public.course_units (course_id, slug, title, summary, position) values ({course}, {q(unit_slug)}, {q(unit_title)}, {q(unit_summary)}, {unit_pos});")
        unit = f"(select id from public.course_units where course_id = {course} and slug = {q(unit_slug)})"
        in_unit = [r for r in rows if r["course_chapters"]["slug"] == chapter_slug]
        in_unit.sort(key=lambda r: ((r["course_chapter_sections"] or {}).get("section_order", 0), r["display_position"]))
        for pos, r in enumerate(in_unit, start=1):
            w(f"insert into public.course_modules (unit_id, module_id, position) values ({unit}, (select id from public.modules where slug = {q(r['videos']['slug'])}), {pos});")
    for pos, slug in enumerate(LIBRARY_EXPLAINERS, start=1):
        w(f"insert into public.course_library (course_id, item_id, section, position) values ({course}, (select id from public.items where slug = {q(slug)}), 'explainer', {pos});")

    print("\n".join(out))


if __name__ == "__main__":
    main()
